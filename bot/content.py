def format_sources() -> str:
    lines = ["<b>Библиотека источников</b>", ""]
    for index, source in enumerate(SOURCES, start=1):
        lines.append(f"{index}. <b>{source['name']}</b>")
        lines.append(source["summary"])
        lines.append(source["url"])
        lines.append("")
    return "\n".join(lines)



