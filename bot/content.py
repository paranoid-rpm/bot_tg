def format_quiz_question(index: int) -> str:
    item = QUIZ[index]
    options = "\n".join([f"{i + 1}. {option}" for i, option in enumerate(item['options'])])
    return f"<b>Вопрос {index + 1} из {len(QUIZ)}</b>\n\n{item['question']}\n\n{options}"



def format_quiz_result(score: int, total: int) -> str:
    if score == total:
        level = "Отлично: ты уверенно ориентируешься в теме."
    elif score >= total // 2 + 1:
        level = "Хорошо: база есть, но стоит повторить спорные разделы."
    else:
        level = "Нужно повторить теорию и пройти тест ещё раз."
    return f"<b>Результат</b>\n\nПравильных ответов: {score} из {total}.\n{level}"
